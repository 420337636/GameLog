# Fix GitHub DNS/hosts (optional helper)
# Requires administrator rights; use tools\fix-github-hosts.cmd to run it.
#
# What it does:
#   1. tests whether https://github.com is actually reachable
#      (if yes, it does nothing and exits - hosts is not needed)
#   2. otherwise fetches up-to-date GitHub IPs from the community mirror
#      (raw.hellogithub.com/hosts, GitHub520 project) or Cloudflare DoH
#   3. backs up hosts, replaces a marked block, flushes DNS
#
# Use -Undo to remove the block and restore DNS behaviour.

param([switch]$Undo)

$ErrorActionPreference = 'Stop'
$hostsPath = Join-Path $env:WINDIR 'System32\drivers\etc\hosts'
$begin = '# ==== GameLog GitHub hosts BEGIN ===='
$end   = '# ==== GameLog GitHub hosts END ===='

function Test-Admin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    (New-Object Security.Principal.WindowsPrincipal $id).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

if (-not (Test-Admin)) {
    Write-Host '[ERROR] Administrator rights required.' -ForegroundColor Red
    Write-Host '        Run tools\fix-github-hosts.cmd instead (it asks for elevation).'
    exit 1
}

function Backup-Hosts {
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $bak = "$hostsPath.bak-$stamp"
    Copy-Item $hostsPath $bak -Force
    Write-Host "[ok] backup: $bak"
}

function Remove-Block([string[]]$lines) {
    $out = New-Object System.Collections.Generic.List[string]
    $skip = $false
    foreach ($l in $lines) {
        if ($l.Trim() -eq $begin) { $skip = $true; continue }
        if ($l.Trim() -eq $end)   { $skip = $false; continue }
        if (-not $skip) { $out.Add($l) }
    }
    return $out
}

function Flush-Dns {
    ipconfig /flushdns | Out-Null
    Write-Host '[ok] DNS cache flushed'
}

if ($Undo) {
    Backup-Hosts
    $lines = [IO.File]::ReadAllLines($hostsPath)
    $clean = Remove-Block $lines
    [IO.File]::WriteAllLines($hostsPath, $clean, (New-Object Text.UTF8Encoding($false)))
    Flush-Dns
    Write-Host '[done] GitHub hosts block removed.'
    exit 0
}

# 1) Is GitHub reachable right now?
try {
    $r = Invoke-WebRequest 'https://github.com' -UseBasicParsing -TimeoutSec 15 -Headers @{ 'User-Agent' = 'Mozilla/5.0' }
    if ($r.StatusCode -eq 200) {
        Write-Host '[skip] https://github.com is reachable (HTTP 200).' -ForegroundColor Green
        Write-Host '       hosts modification is NOT needed right now.'
        exit 0
    }
} catch {
    Write-Host "[warn] GitHub test failed: $($_.Exception.Message)"
}

# 2) Get fresh IPs
$entries = @()
try {
    Write-Host '[..] fetching IP list from raw.hellogithub.com'
    $txt = (Invoke-WebRequest 'https://raw.hellogithub.com/hosts' -UseBasicParsing -TimeoutSec 20).Content
    $entries = $txt -split "`r?`n" | Where-Object {
        $_ -match '^\s*\d{1,3}(\.\d{1,3}){3}\s+' -and $_ -match 'github'
    } | ForEach-Object { $_.Trim() }
    Write-Host "[ok] got $($entries.Count) entries"
} catch {
    Write-Host "[warn] mirror failed: $($_.Exception.Message)"
}

if ($entries.Count -eq 0) {
    Write-Host '[..] falling back to Cloudflare DoH'
    $names = @(
        'github.com', 'api.github.com', 'codeload.github.com',
        'raw.githubusercontent.com', 'objects.githubusercontent.com',
        'gist.github.com', 'github.githubassets.com'
    )
    foreach ($n in $names) {
        try {
            $uri = "https://cloudflare-dns.com/dns-query?name=$n&type=A"
            $resp = Invoke-RestMethod $uri -Headers @{ Accept = 'application/dns-json' } -TimeoutSec 15
            $ips = $resp.Answer | Where-Object { $_.type -eq 1 } | Select-Object -ExpandProperty data -Unique
            foreach ($ip in $ips) { $entries += "$ip`t$n" }
        } catch {
            Write-Host "[warn] DoH failed for $n"
        }
    }
    Write-Host "[ok] got $($entries.Count) entries from DoH"
}

if ($entries.Count -eq 0) {
    Write-Host '[ERROR] Could not obtain any IP address. Nothing changed.' -ForegroundColor Red
    exit 1
}

# 3) Apply
Backup-Hosts
$lines = [IO.File]::ReadAllLines($hostsPath)
$clean = Remove-Block $lines

$block = New-Object System.Collections.Generic.List[string]
$block.Add('')
$block.Add($begin)
$block.Add('# generated by GameLog tools/fix-github-hosts.ps1')
$block.Add('# remove with: tools\fix-github-hosts.cmd -Undo')
foreach ($e in $entries) { $block.Add($e) }
$block.Add($end)

$all = New-Object System.Collections.Generic.List[string]
foreach ($l in $clean) { $all.Add($l) }
foreach ($l in $block) { $all.Add($l) }

[IO.File]::WriteAllLines($hostsPath, $all, (New-Object Text.UTF8Encoding($false)))
Flush-Dns

Write-Host '[done] hosts updated. Test with: https://github.com' -ForegroundColor Green
Write-Host '       If it still fails, remove the block with -Undo and use a proxy instead.'
